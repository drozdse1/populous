static uint8_t title_score[sizeof title_score_rom];   /* pulse waves are rewritten */
static int title_score_ready;
static int8_t title_silent[0x200];   /* $39A(A3), LEN $100 */

typedef struct {
    int8_t *data;
    int32_t loop;
    uint16_t length, base, volume, vib_div, vib, pwm_max, pwm_min;
} Instrument;

typedef struct {                     /* $302(A3) + v*$26 */
    uint16_t flags, counter, period, pwm;    /* +0, +10, +12, +24 */
    uint8_t note, latched;                   /* +2, +16 */
    int8_t slide;                            /* +14 */
    int instrument;                          /* +18 */
    int event;                               /* port: last note (1) / rest (2) */
    uint32_t pattern, list, index, vib, vib_start;   /* +4, +8, +C, +1C, +20 */
} Voice;

static Instrument instruments[INSTRUMENTS];
static Voice voices[TITLE_VOICES];
static uint8_t tempo;                /* $300(A3) */
static int playing;                  /* $2FE(A3) */

static uint16_t be16(const uint8_t *p) { return (uint16_t)(p[0] << 8 | p[1]); }
static uint32_t be32(const uint8_t *p) { return (uint32_t)be16(p) << 16 | be16(p+2); }

/* A3-relative address -> transcribed byte, NULL outside the image. */
static uint8_t *score(uint32_t offset, size_t bytes)
{
    uint32_t address = A3_BASE + offset;
    if (address < SCORE_BASE || address - SCORE_BASE > sizeof title_score - bytes) return NULL;
    return title_score + (address - SCORE_BASE);
}

static int fail(char *error, size_t size, const char *text)
{
    if (error && size) snprintf(error, size, "%s", text);
    return 0;
}

void title_bank_free(TitleBank *bank)
{
    if (!bank) return;
    free(bank->pcm);
    memset(bank, 0, sizeof *bank);
}

/* Strict: the eight records SUB_2F9C walks (asm:2650-2662) must consume the
 * file, which must fit the 0x1c01e Read (asm:2445-2450). DIVU needs a rate
 * whose 0x369e99/rate quotient fits a word. */
int title_bank_parse(TitleBank *bank, const uint8_t *data, size_t size, char *error, size_t error_size)
{
    TitleBank b;
    memset(&b, 0, sizeof b);
    if (!bank || !data) return fail(error, error_size, "no popsam data");
    if (size > TITLE_POPSAM_SIZE) return fail(error, error_size, "popsam larger than the 0x1c01e read");
    size_t at = 0;
    for (int index = 0; index < TITLE_SAMPLES; ++index) {
        if (size - at < 6) return fail(error, error_size, "truncated popsam");
        uint32_t length = be32(data + at);
        uint16_t rate = be16(data + at + 4);
        if (!rate || 0x369e99u / rate > 0xffffu) return fail(error, error_size, "sample rate overflows the DIVU period");
        if (length > size - at - 6) return fail(error, error_size, "truncated popsam");
        b.samples[index] = (TitleSample){(uint32_t)(at + 6), length, rate};
        at += 6 + length;
    }
    if (at != size) return fail(error, error_size, "unexpected popsam size");
    b.pcm = malloc(size);
    if (!b.pcm) return fail(error, error_size, "out of memory");
    memcpy(b.pcm, data, size);
    b.size = size;
    *bank = b;
    return 1;
}

/* SUB_3046 asm:2699-2705: playing off, DMACON $000f. */
void title_music_stop(void)
{
    playing = 0;
    for (int channel = 0; channel < TITLE_VOICES; ++channel) audio_abort(channel);
}

int title_music_playing(void) { return playing; }
int title_music_tempo(void) { return tempo; }

/* SUB_2F9C asm:2645-2698. */
int title_music_start(const TitleBank *bank, int song)
{
    if (!bank || !bank->pcm) return 0;
    title_music_stop();
    if (!title_score_ready) { memcpy(title_score, title_score_rom, sizeof title_score); title_score_ready = 1; }
    const uint8_t *entry = score(0x86e + (uint32_t)song * 0x12, 0x12);
    if (song < 0 || !entry) return 0;
    for (int index = 0; index < INSTRUMENTS; ++index) {
        const uint8_t *p = title_score + 0x6e + index * 32;
        Instrument *in = &instruments[index];
        *in = (Instrument){NULL, (int32_t)be32(p+4), be16(p+8), be16(p+0xc), be16(p+0xe), be16(p+0x10),
                           be16(p+0x12), be16(p+0x14), be16(p+0x16)};
        if (index < TITLE_SAMPLES) {         /* asm:2650-2662 */
            const TitleSample *s = &bank->samples[index];
            in->data = bank->pcm + s->offset;
            in->length = (uint16_t)(s->length >> 1);
            in->base = (uint16_t)(0x369e99u / s->rate);
        }
    }
    for (int index = 0; index < 3; ++index) {   /* LAB_3594 -> LAB_3740 (asm:2663-2669) */
        uint8_t *wave = score(be32(title_score + 0x62 + index * 4), 2u * instruments[13 + index].length);
        instruments[13 + index].data = (int8_t *)wave;
    }
    tempo = entry[1];
    for (int v = 0; v < TITLE_VOICES; ++v) {   /* asm:2672-2690 */
        Voice *voice = &voices[v];
        memset(voice, 0, sizeof *voice);
        voice->counter = 1; voice->instrument = -1;
        /* Port: $16 is never set here; the first pass would latch from a
         * stale instrument pointer while DMA is off, so start latched. */
        voice->latched = 1;
        voice->list = be32(entry + 2 + v * 4);
        const uint8_t *first = score(voice->list, 4);
        if (!first) return 0;
        voice->pattern = be32(first); voice->index = 4;
    }
    playing = 1;
    return 1;
}

static int wave_inside(const int8_t *p)
{
    return (const uint8_t *)p >= title_score && (const uint8_t *)p < title_score + sizeof title_score;
}

/* LAB_30E4..LAB_31EA asm:2732-2834. */
static void title_events(int channel, Voice *voice)
{
    voice->flags = 0;
    for (int guard = 0; guard < 256; ++guard) {
        const uint8_t *p = score(voice->pattern, 2);
        if (!p) { voice->counter = 0; audio_abort(channel); return; }
        uint8_t command = p[0];
        ++voice->pattern;
        if (command < 0x80) {                /* LAB_3186: duration, note */
            voice->counter = (uint16_t)(command * tempo);
            voice->note = p[1]; ++voice->pattern; voice->event = 1;
            if (voice->instrument < 0) return;
            Instrument *in = &instruments[voice->instrument];
            voice->pwm = in->pwm_min;
            voice->vib = voice->vib_start;
            const uint8_t *step = score((uint32_t)(SCORE_BASE - A3_BASE) + 2u * voice->note, 2);
            voice->period = (uint16_t)(((uint32_t)(step ? be16(step) : 0) * in->base) >> 10);
            if (in->data) audio_paula_start(channel, in->data, 2u * in->length, voice->period, in->volume);
            voice->latched = 0;
            return;
        }
        if (command == 0x80) {               /* LAB_3110: instrument */
            if (p[1] < INSTRUMENTS) {
                voice->instrument = p[1];
                voice->vib = voice->vib_start = 0x37a0u - A3_BASE + instruments[p[1]].vib;
            }
            ++voice->pattern;
        } else if (command == 0x81) {        /* LAB_3158: slide for the next note */
            voice->slide = (int8_t)p[1]; voice->flags |= 2; ++voice->pattern;
        } else if (command == 0x82) {        /* LAB_3132: rest */
            voice->counter = (uint16_t)(p[1] * tempo); ++voice->pattern; voice->event = 2;
            audio_paula_latch(channel, title_silent, sizeof title_silent);
            return;
        } else if (command == 0x84) {        /* LAB_3164: next pattern, wrap at 0 */
            const uint8_t *next = score(voice->list + voice->index, 4);
            voice->index += 4;
            if (!next || !be32(next)) { next = score(voice->list, 4); voice->index = 4; }
            if (!next) return;
            voice->pattern = be32(next);
        }                                    /* $83 and others: skipped */
    }
}

/* LAB_31F0..LAB_3292 asm:2835-2896: slide, vibrato, pulse width. */
static void title_effects(int channel, Voice *voice)
{
    if (voice->instrument < 0) return;
    Instrument *in = &instruments[voice->instrument];
    if (voice->flags & 2) {
        voice->period = (uint16_t)(voice->period + voice->slide);
        audio_paula_period(channel, voice->period);
    }
    if (in->vib_div) {
        int16_t quotient = (int16_t)(voice->period / in->vib_div);
        const uint8_t *p = score(voice->vib, 1);
        if (p && *p == 0x84) { voice->vib = voice->vib_start; p = score(voice->vib, 1); }
        if (p) {
            ++voice->vib;
            audio_paula_period(channel, (uint16_t)(voice->period + quotient * (int8_t)*p));
        }
    }
    if (!in->pwm_max || !in->data || !wave_inside(in->data)) return;
    uint16_t at = voice->pwm;
    int8_t value;
    if (!(voice->flags & 4)) {
        ++at;
        if (at > in->pwm_max) { voice->flags |= 4; value = 0x3c; } else value = 0;
    } else {
        --at;
        if (at > in->pwm_min) value = 0x3c; else { voice->flags &= (uint16_t)~4; value = 0; }
    }
    if (wave_inside(in->data + at)) in->data[at] = value;
    voice->pwm = at;
}

void title_music_vbi(void)
{
    if (!playing) return;
    audio_lock();
    for (int channel = TITLE_VOICES - 1; channel >= 0; --channel) {
        Voice *voice = &voices[channel];
        if (!voice->latched && voice->instrument >= 0) {   /* asm:2722-2731 */
            Instrument *in = &instruments[voice->instrument];
            voice->latched = 1;
            if (!in->loop) audio_paula_latch(channel, title_silent, sizeof title_silent);
            else if (in->loop > 0 && in->data && (uint32_t)in->loop < 2u * in->length)
                audio_paula_latch(channel, in->data + in->loop,
                                  2u * (uint16_t)(in->length - ((uint16_t)in->loop >> 1)));
        }
        if (!--voice->counter) { title_events(channel, voice); continue; }
        if (voice->counter == 1) audio_abort(channel);    /* DMACON off, asm:2737-2741 */
        title_effects(channel, voice);
    }
    audio_unlock();
}

int title_music_voice(int v, TitleVoice *out)
{
    if (v < 0 || v >= TITLE_VOICES || !out) return 0;
    const Voice *voice = &voices[v];
    *out = (TitleVoice){voice->counter, voice->period, voice->flags, voice->note, voice->instrument,
                        voice->event, voice->pattern};
    return 1;
}
